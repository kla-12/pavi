const { Octokit } = require('@octokit/rest');
const logger = require('../utils/logger');
const fs = require('fs');
const path = require('path');

async function publishPR(issuePayload, plan, swarmResult) {
    const token = process.env.GITHUB_TOKEN;
    if (!token) {
        throw new Error('GITHUB_TOKEN not configured.');
    }

    const octokit = new Octokit({ auth: token });
    const repoInfo = issuePayload.repository;
    const owner = repoInfo.owner.login;
    const repo = repoInfo.name;
    const defaultBranch = process.env.GITHUB_DEFAULT_BRANCH || repoInfo.default_branch || 'main';

    const branchName = `pavi/issue-${issuePayload.issue.number}-${Date.now()}`;

    // Get default branch SHA
    const ref = await octokit.rest.git.getRef({
        owner,
        repo,
        ref: `heads/${defaultBranch}`
    });
    const baseSha = ref.data.object.sha;

    // Create new branch
    await octokit.rest.git.createRef({
        owner,
        repo,
        ref: `refs/heads/${branchName}`,
        sha: baseSha
    });

    const paviProjectRoot = path.join(__dirname, '../..');

    // Commit all plan files
    const filesToCommit = plan.filesContext || [];
    for (const filePath of filesToCommit) {
        const fullPath = path.join(paviProjectRoot, filePath);
        if (fs.existsSync(fullPath)) {
            const content = fs.readFileSync(fullPath, 'utf8');
            const encodedContent = Buffer.from(content).toString('base64');
            
            let fileSha;
            try {
                const { data } = await octokit.rest.repos.getContent({
                    owner,
                    repo,
                    path: filePath,
                    ref: branchName
                });
                if (!Array.isArray(data)) {
                    fileSha = data.sha;
                }
            } catch (err) {
                // File does not exist yet (404)
            }
            
            await octokit.rest.repos.createOrUpdateFileContents({
                owner,
                repo,
                path: filePath,
                message: `Pavi AI: Update ${filePath} for Issue #${issuePayload.issue.number}`,
                content: encodedContent,
                branch: branchName,
                sha: fileSha
            });
        }
    }

    // Create Pull Request
    const prBody = `## Pavi Autonomous CI/CD
This Pull Request was automatically generated by Pavi to resolve Issue #${issuePayload.issue.number}.

**Objective:**
${plan.objective}

**Execution Summary:**
${swarmResult ? (swarmResult.output || '').substring(0, 500) + '...' : 'No swarm output'}

### Files Modified:
${filesToCommit.map(f => `- \`${f}\``).join('\n')}
`;

    const pr = await octokit.rest.pulls.create({
        owner,
        repo,
        title: `Fix: ${plan.objective}`,
        head: branchName,
        base: defaultBranch,
        body: prBody
    });

    return {
        url: pr.data.html_url,
        number: pr.data.number,
        branch: branchName
    };
}

module.exports = {
    publishPR
};
